// Порядок місць у «Де:» — згори донизу.
const ORDER = ['mind', 'head', 'vertigo', 'eyes', 'ears', 'nose', 'face', 'mouth', 'teeth', 'throat', 'stomach', 'abdomen', 'rectum', 'urinary',
  'female', 'male', 'breath', 'cough', 'heart', 'back', 'limbs', 'skin', 'sleep', 'fever'];
const byKey = new Map(BASE.concat(MORE).map(p => [p.key, p]));
export const PLACES = ORDER.map(k => byKey.get(k));

const NEG = new Set(['не', 'ни', 'без', 'нет']);
const WORD_RE = /[а-яёa-z0-9-]+/g;

function compile(list) {
  return (list || []).map(w => w.startsWith('=') ? { exact: w.slice(1).replace(/ё/g, 'е') } : { pre: w.replace(/ё/g, 'е') });
}
const hitWord = (pats, w) => pats.some(p => (p.exact ? w === p.exact : w.startsWith(p.pre)));
// Слова речення, не заперечені: перед ним (до двох слів) немає «не/ни/без/нет».
function hits(words, pats) {
  for (let i = 0; i < words.length; i++) {
    if (!hitWord(pats, words[i])) continue;
    if (NEG.has(words[i - 1]) || NEG.has(words[i - 2])) continue;
    return true;
  }
  return false;
}

// Готує ознаки до зіставлення: [{ place, group, item, any, with }]
export function compileFacets() {
  const out = [];
  for (const pl of PLACES) {
    pl.groups.forEach((g, gi) => {
      for (const it of g.items) out.push({ place: pl, gi, item: it, key: pl.key + '.' + it.key, any: compile(it.any), with: compile(it.with), need: pl.need || {} });
    });
  }
  return out;
}

// Чи підходить речення ознаці; sec — назва розділу (російська) речення.
export function matchSentence(f, sent, sec) {
  const words = (sent.toLowerCase().replace(/ё/g, 'е').match(WORD_RE) || []);
  const need = f.need[sec];
  if (need && !hits(words, compile(need))) return false;
  if (!hits(words, f.any)) return false;
  if (f.with.length && !words.some(w => hitWord(f.with, w))) return false;
  return true;
}
